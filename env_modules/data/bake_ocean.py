"""Rasterize Natural Earth v5.1.2 ocean polygons at pixel centres, north first.
Source: https://github.com/nvkelso/natural-earth-vector/blob/v5.1.2/geojson/ne_110m_ocean.geojson
Public domain. Rebuild the checked-in row spans with Python's standard library.
"""
import json
import math
from pathlib import Path

root = Path(__file__).resolve().parent
width, height = 2048, 1024
rows = [[] for _ in range(height)]
for feature in json.loads((root / "ne_110m_ocean.geojson").read_text())["features"]:
    geometry = feature["geometry"]
    polygons = geometry["coordinates"]
    if geometry["type"] == "Polygon":
        polygons = [polygons]
    for rings in polygons:
        crossings = [[] for _ in range(height)]
        for ring in rings:
            for (ax, ay), (bx, by) in zip(ring, ring[1:]):
                if by == ay:
                    continue
                north = (90 - max(ay, by)) * height / 180
                south = (90 - min(ay, by)) * height / 180
                for j in range(max(0, math.ceil(north-.5)), min(height, math.ceil(south-.5))):
                    lat = 90 - (j+.5) * 180 / height
                    lon = ax + (lat-ay) * (bx-ax) / (by-ay)
                    crossings[j].append(max(0,min(width,math.ceil((lon+180)*width/360-.5))))
        for row, xs in zip(rows, crossings):
            xs.sort()
            assert len(xs) % 2 == 0
            row.extend((a,b) for a,b in zip(xs[::2],xs[1::2]) if a<b)

with (root / "OceanSpans.inc").open("w") as output:
    output.write("// Generated by bake_ocean.py, one count and [begin,end) pairs per row.\n")
    for row in rows:
        output.write(",".join(map(str,[len(row), *(x for span in row for x in span)])) + ",\n")
